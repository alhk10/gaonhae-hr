import { isSupabaseWrite } from './accessAutoRefresh';
const B = 'https://x.supabase.co/rest/v1/';
let fail = 0;
const t = (name: string, got: boolean, want: boolean) => { if (got !== want) { fail++; console.error('FAIL', name); } };
t('saving settings refreshes', isSupabaseWrite(B + 'rpc/access_grading_branch_score_settings_set', 'POST'), true);
t('marking attendance refreshes', isSupabaseWrite(B + 'rpc/access_attendance_mark', 'POST'), true);
t('loading grading list does not', isSupabaseWrite(B + 'rpc/get_public_grading_list', 'POST'), false);
t('loading attendance week does not', isSupabaseWrite(B + 'rpc/access_attendance_week', 'POST'), false);
t('table edits refresh', isSupabaseWrite(B + 'invoices?id=eq.1', 'PATCH'), true);
t('table reads do not', isSupabaseWrite(B + 'invoices?select=*', 'GET'), false);
if (fail) throw new Error(`${fail} failed`);
console.log('all passed');
