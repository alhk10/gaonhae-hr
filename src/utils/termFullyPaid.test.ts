import { isTermFullyPaid } from './termFullyPaid';
const eq = (a: unknown, b: unknown, m: string) => { if (a !== b) throw new Error(`${m}: ${a} !== ${b}`); };
eq(isTermFullyPaid([{ plan: 'four_weeks', weeks: 4 }], 12), false, '4 of 12 weeks is not paid');
eq(isTermFullyPaid([1, 2, 3].map(() => ({ plan: 'four_weeks', weeks: 4 })), 12), true, 'three 4-week plans cover 12 weeks');
eq(isTermFullyPaid([{ quantity: 12 }], 12), true, 'full-term quantity is paid');
eq(isTermFullyPaid([{ quantity: 3 }], 12), false, "Finn: 3 of 12 weeks is not paid");
eq(isTermFullyPaid([{ quantity: 6 }], 6), true, 'late joiner paying all remaining weeks is paid');
console.log('termFullyPaid ok');

import { termCoverage } from './termFullyPaid';
const T4 = { termStart: '2026-09-29', termEnd: '2026-12-20', termWeeks: 12 };
const ronan = termCoverage({ ...T4, firstInvoiceDate: '2026-09-25', paidWeeks: 4, today: '2026-10-15' });
eq(ronan.paidToday, true, 'Ronan 4 weeks: paid in October');
eq(ronan.coveredUntil, '2026-10-26', 'Ronan covered until 26/10');
eq(termCoverage({ ...T4, firstInvoiceDate: '2026-09-25', paidWeeks: 4, today: '2026-11-12' }).paidToday, false, 'Ronan unpaid in November');
eq(ronan.remainingWeeks, 8, 'Ronan owes 8 more weeks');
eq(ronan.gradingEligible, false, '4 of 12 weeks is below 50% for grading');
eq(termCoverage({ ...T4, firstInvoiceDate: '2026-09-25', paidWeeks: 6, today: '2026-11-12' }).gradingEligible, true, '6 of 12 weeks (50%) can grade');
const finn = termCoverage({ ...T4, firstInvoiceDate: '2026-11-11', paidWeeks: 3, today: '2026-11-12' });
eq(finn.isLateJoiner, true, 'Finn joined late');
eq(finn.paidToday, true, 'Finn paid today');
eq(finn.coveredUntil, '2026-12-01', 'Finn covered until 01/12');
eq(finn.remainingWeeks, 3, 'Finn owes 3 more weeks');
eq(finn.gradingEligible, true, 'late joiner exempt from 50% rule');
eq(termCoverage({ ...T4, firstInvoiceDate: '2026-09-20', paidWeeks: 12, today: '2026-12-15' }).paidToday, true, 'full term paid until term end');
console.log('termCoverage ok');
